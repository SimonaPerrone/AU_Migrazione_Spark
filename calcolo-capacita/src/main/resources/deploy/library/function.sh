
needs_arg()
{
  if [ -z "$OPTARG" ]; then
    die "No arg for --$OPT option"
  fi
}
check_data_calc()
{
  data_calc=$1
  if ! [[ "$(date -d "${data_calc}" '${application.sh.date.format}' 2>/dev/null)" == "${data_calc}" ]]; then
    die "Bad data_calc param: ${data_calc} is not '${application.sh.date.format}' format."
  fi

}
get_curr_date() {
  date '${application.sh.date.format}'
}
check_integer_numer()
{
  number=$1
  var=$2
  if ! [[ "$number" =~ ^[0-9]+$ ]]
    then
        die "Bad input param, ${var}: integers only"
fi
}
check_x()
{
  x=$1
  if [[ x -le 1 ]];
  then
    die "Bad input param, x: {$x} at least > 1"
  fi
}
check_y()
{
  y=$1
  if [[ y -le 1 ]];
  then
    die "Bad input param, x: {$y} at least > 1"
  fi
}
print_help()
{
  log "calcolo-capacita-main.sh"
  log "                                [-h|--help]"
  log "                                [-v|--verbose]"
  log "                                [-a|--automatic]"
  log "                                [-d|--data-calc format=[${application.sh.date.format}]"
  log "                                [-x|number type=integer"
  log "                                [-y|number type=integer"

}
print_variables()
{
    log "Script variables:"
    log "PRINT_HELP=\"${PRINT_HELP}\""
    log "PRINT_VERBOSE=\"${PRINT_VERBOSE}\""
    log "AUTOMATIC=\"${AUTOMATIC}\""
    log "DATA_CALC=\"${DATA_CALC}\""
    log "X=\"${X}\""
    log "Y=\"${Y}\""
    log ""
}
check_combination_input_param()
{
  # Se viene specificato un timestamp allora non sono ammessi altri parametri
  if ! [ -v DATA_CALC ] || ! [ -v X ] || ! [ -v Y ]  ; then
    die "Bad param : you must pass -d and -x and -y"
  fi
}
check_combination_input_param_import()
{
  # Se viene specificato un timestamp allora non sono ammessi altri parametri
  if  ! [ -v DATA_CALC ]   ; then
    die "Bad param : you must pass -d"
  fi
}
create_var()
{
  if [[ ${PRINT_HELP} ]]; then
    print_help
    exit 0
  fi
   if [[ ${PRINT_VERBOSE} ]]; then
    print_variables
  fi
  if [[ ${AUTOMATIC} ]]; then
    DATA_CALC=$(get_curr_date)
    log "new DATA_CALC generated by -a: $DATA_CALC"
  fi
  check_combination_input_param
  check_data_calc $DATA_CALC
  check_integer_numer $X "X"
  check_integer_numer $Y "Y"
  check_x $X
  check_x $Y
}
catch_getopts()
{
local OPTIND
while getopts hvt:d:x:y:a:-: OPT; do
  if [ "$OPT" = "-" ]; then
    OPT="${OPTARG%%=*}"
    OPTARG="${OPTARG#$OPT}"
    OPTARG="${OPTARG#=}"
  fi
  case "$OPT" in
  h | help) PRINT_HELP="true" ;;
  v | verbose) PRINT_VERBOSE="true" ;;
  a | automatic) AUTOMATIC="true" ;;
  d | data-calc) needs_arg; DATA_CALC="$OPTARG";;
  x ) needs_arg; X="$OPTARG";;
  y ) needs_arg; Y="$OPTARG";;
  ??*) die "Illegal option --$OPT" ;;
  \?) exit 2 ;;
  esac
done
shift $((OPTIND-1))
}
